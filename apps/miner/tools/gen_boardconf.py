"""Lay1 descriptor generator: boardconf.ini -> boardconf.h.

Usage:
    gen_boardconf.py <boardconf.ini> <out/boardconf.h>
    gen_boardconf.py --sh <boardconf.ini>
    gen_boardconf.py --get KEY <boardconf.ini>
The first section in the file is the descriptor.
"""
import os
import re
import shlex
import sys

# "[name]" section header line.
_SEC = re.compile(r"^\s*\[(?P<name>[^\]]+)\]\s*$")
# "KEY = value" line; the value is taken up to trailing whitespace.
_KV = re.compile(r"^\s*(?P<k>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?P<v>.*?)\s*$")

# Descriptor keys holding a quoted C string.
STR_KEYS = ("PROD_NAME", "MODEL", "HW_TYPE", "SW_TYPE", "BOARD")
# Descriptor keys holding a positive integer.
NUM_KEYS = ("HBOARD_COUNT", "FAN_COUNT", "MAX_ASIC_ON_SINGLE_HASH",
            "VOL_ENUM", "INIT_FREQ", "ADJ_FREQ_INTERVAL", "FREQ_INTERVAL")
# Core-rail voltage window, positive integers in the board's rail units.
VOL_KEYS = ("VOL_MIN", "VOL_MAX")
# Keys printed by --sh as shell assignments.
SH_KEYS = ("HW_TYPE", "SW_TYPE")
# 0/1 build switches read through --get; not emitted into boardconf.h.
FEATURE_KEYS = ("SUPPORT_LCD", "SUPPORT_BLE")


def _strip_comment(s):
    quote = False
    i = 0
    while i < len(s):
        c = s[i]
        if quote and c == "\\":
            i += 2
            continue
        if c == '"':
            quote = not quote
        elif not quote and (c in ";#" or s.startswith("//", i)):
            return s[:i].strip()
        i += 1
    return s.strip()


def parse(path):
    """path -> ordered list of (section, [(key, value), ...])."""
    secs, cur = [], None
    with open(path, errors="replace") as f:
        for raw in f:
            line = raw.rstrip("\n")
            m = _SEC.match(line)
            if m:
                cur = (m["name"], [])
                secs.append(cur)
                continue
            if cur is None:
                continue
            mk = _KV.match(line)
            if mk:
                if any(k == mk["k"] for k, _ in cur[1]):
                    sys.exit("gen_boardconf: [%s] %s is set more than once in %s"
                             % (cur[0], mk["k"], path))
                cur[1].append((mk["k"], _strip_comment(mk["v"])))
    return secs


def _unparen(v):
    v = v.strip()
    while v.startswith("(") and v.endswith(")"):
        v = v[1:-1].strip()
    return v


def check(name, d):
    """Fail-closed validation of the descriptor's own keys."""
    errs = []
    for k in STR_KEYS:
        if k not in d:
            errs.append("missing %s (a quoted string)" % k)
        elif not _unparen(d[k]).startswith('"'):
            errs.append("%s must be a quoted string, got %r" % (k, d[k]))
    for k in NUM_KEYS:
        if k not in d:
            errs.append("missing %s (a positive integer)" % k)
        else:
            v = _unparen(d[k])
            if not v.isdigit() or int(v) < 1:
                errs.append("%s must be a positive integer, got %r" % (k, d[k]))
    for k in VOL_KEYS:
        if k not in d:
            errs.append("missing %s (a positive integer)" % k)
        else:
            v = _unparen(d[k])
            if not v.isdigit() or int(v) < 1:
                errs.append("%s must be a positive integer, got %r" % (k, d[k]))
    for k in FEATURE_KEYS:
        if k not in d:
            errs.append("missing %s (0 or 1)" % k)
        elif d[k] not in ("0", "1"):
            errs.append("%s must be 0 or 1, got %r" % (k, d[k]))
    known = STR_KEYS + NUM_KEYS + VOL_KEYS + FEATURE_KEYS
    unknown = [k for k in d if k not in known]
    if unknown:
        errs.append("key(s) %s belong in hal/board/board_<BOARD>.h, not in the "
                    "descriptor" % ", ".join(sorted(unknown)))
    if errs:
        sys.exit("gen_boardconf: [%s] descriptor is invalid:\n  - %s"
                 % (name, "\n  - ".join(errs)))


def emit_h(section_name, kvs):
    d = dict(kvs)
    board = _unparen(d["BOARD"]).strip('"')
    out = [
        "/* GENERATED by tools/gen_boardconf.py from boardconf.ini — do not edit. */",
        "#ifndef BOARDCONF_H",
        "#define BOARDCONF_H",
        "",
        '#define BOARDCONF_SECTION "%s"' % section_name,
        "",
    ]
    for k, v in kvs:
        if k in FEATURE_KEYS or k == "BOARD":
            continue
        out.append("#define %s" % k if v == "" else "#define %s %s" % (k, v))
    out += [
        "",
        '#define BOARD_HEADER "board_%s.h"' % board,
        "#include BOARD_HEADER",
        '#include "board_assert.h"',
        "",
        "#endif /* BOARDCONF_H */",
        "",
    ]
    return "\n".join(out)


def emit_sh(section_name, kvs):
    d = dict(kvs)
    out = []
    for k in SH_KEYS:
        v = _unparen(d[k]).strip('"')
        if not v:
            sys.exit("gen_boardconf: [%s] %s is empty; it is the single source "
                     "of the value stamped into the u-boot env and the .aup "
                     "header" % (section_name, k))
        out.append("%s=%s\n" % (k, shlex.quote(v)))
    return "".join(out)


def main(argv):
    usage = ("usage: gen_boardconf.py <boardconf.ini> <out/boardconf.h>\n"
             "       gen_boardconf.py --sh <boardconf.ini>\n"
             "       gen_boardconf.py --get KEY <boardconf.ini>")
    args = argv[1:]
    want_sh = args[:1] == ["--sh"]
    if want_sh:
        args = args[1:]
    get_key = None
    if args[:1] == ["--get"]:
        if len(args) < 2:
            sys.exit("gen_boardconf: --get needs a KEY")
        get_key = args[1]
        args = args[2:]
    for a in args:
        if a.startswith("-"):
            sys.exit("gen_boardconf: unknown argument %r\n%s" % (a, usage))
    npos = 1 if want_sh or get_key else 2
    if len(args) != npos:
        sys.exit(usage)
    ini = args[0]
    out_h = None if npos == 1 else args[1]

    secs = parse(ini)
    if not secs:
        sys.exit("gen_boardconf: no [SECTION] found in %s" % ini)
    name, kvs = secs[0]

    check(name, dict(kvs))

    if want_sh:
        sys.stdout.write(emit_sh(name, kvs))
        return 0

    if get_key:
        d = dict(kvs)
        if get_key not in d:
            sys.exit("gen_boardconf: [%s] has no key %s" % (name, get_key))
        sys.stdout.write(_unparen(d[get_key]) + "\n")
        return 0

    os.makedirs(os.path.dirname(os.path.abspath(out_h)), exist_ok=True)
    with open(out_h, "w") as f:
        f.write(emit_h(name, kvs))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
